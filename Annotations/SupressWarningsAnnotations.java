/*
 * @SuppressWarnings is a predefined (built-in) Java annotation.
 *
 * It is used to tell the compiler or development tools to suppress
 * specific categories of warnings in a particular part of the code.
 *
 * It does NOT fix the underlying problem. It only suppresses the
 * warning from being reported.
 *
 * @SuppressWarnings can be used at different levels:
 * 1. Class level
 * 2. Method level
 * 3. Constructor level
 * 4. Field level
 * 5. Local variable declaration level
 *
 * The scope of suppression depends on where we place the annotation.
 *
 * Common examples:
 * @SuppressWarnings("deprecation")
 * @SuppressWarnings("unused")
 * @SuppressWarnings("all")
 * @SuppressWarnings({"deprecation", "unused"})
 *
 *
 * 1. @SuppressWarnings("deprecation")
 *
 * It suppresses warnings caused by using deprecated classes,
 * methods, constructors, or fields.
 *
 * Deprecated means that an element is still available but its use
 * is discouraged, usually because a better alternative exists.
 *
 * Use this when we intentionally need to use a deprecated API,
 * for example, when maintaining legacy code.
 *
 * However, replacing the deprecated API with its recommended
 * alternative is preferable whenever possible.
 *
 *
 * 2. @SuppressWarnings("unused")
 *
 * It suppresses unused-element warnings in development tools
 * that support this warning category.
 *
 * For example, an IDE may warn us when a variable, field, or
 * method is declared but never used.
 *
 * Important:
 * The standard Java compiler (javac) generally does not report
 * unused local variables as warnings by default.
 *
 * Therefore, this suppression is mainly useful in IDEs and
 * static analysis tools that recognize the "unused" category.
 *
 * Use it when an element is intentionally unused.
 *
 *
 * 3. @SuppressWarnings("all")
 *
 * It requests suppression of all warning categories recognized
 * by the compiler for the annotated scope.
 *
 * Use it rarely, preferably in a small and carefully reviewed
 * section of legacy or generated code.
 *
 * Avoid using "all" unnecessarily because it may hide useful
 * warnings that could help us identify problems.
 *
 *
 * 4. Suppressing multiple warning categories
 *
 * We can suppress multiple warning categories by passing an
 * array of strings:
 *
 * @SuppressWarnings({"deprecation", "unused"})
 *
 * This requests suppression of both deprecation and unused
 * warnings wherever those categories are recognized.
 *
 *
 * Class-level vs Method-level suppression:
 *
 * Class level:
 * @SuppressWarnings("deprecation")
 * public class Example { }
 *
 * The suppression applies to the relevant code within the class.
 *
 * Method level:
 * @SuppressWarnings("deprecation")
 * public void exampleMethod() { }
 *
 * The suppression applies to the annotated method.
 *
 * If a warning is produced inside main(), placing the annotation
 * on main() is usually sufficient for that method's scope.
 *
 * If the class-level annotation already covers the warning,
 * adding the same annotation to the method is redundant.
 *
 *
 * Best practice:
 *
 * 1. Fix warnings whenever possible instead of suppressing them.
 * 2. Use the narrowest scope necessary.
 * 3. Suppress only the warning categories that are needed.
 * 4. Avoid "all" unless there is a strong reason.
 * 5. Remember that suppressing a warning does not change
 *    the actual runtime behavior of the program.
 */

class Mobile {

    @Deprecated
    public void dummyMethod() {
        System.out.println("This is a dummy Method");
    }
}

/*
 * Here, we can use @SuppressWarnings at the class level.
 *
 * The deprecation warning generated by calling dummyMethod()
 * is suppressed within this class.
 */

@SuppressWarnings("deprecation")
public class SupressWarningsAnnotations {

    /*
     * We can also use @SuppressWarnings at the method level.
     *
     * This suppression applies to the relevant code inside main().
     *
     * Since the class already has @SuppressWarnings("deprecation"),
     * adding the same annotation here is redundant.
     */

    @SuppressWarnings("deprecation")
    public static void main(String[] args) {

        Mobile mobObj = new Mobile();

        // Calling a deprecated method.
        // The deprecation warning is suppressed.
        mobObj.dummyMethod();

        /*
         * Example of suppressing an unused-variable warning.
         *
         * Some IDEs and analysis tools may warn us that the variable
         * is declared but never used.
         *
         * Standard javac generally does not report this warning
         * for local variables by default.
         */

        @SuppressWarnings("unused")
        int number = 100;

        /*
         * Example of suppressing all recognized warning categories
         * for this method.
         *
         * Use this cautiously because it may hide useful warnings.
         */

        helperMethod();
    }

    /*
     * @SuppressWarnings("unused") tells tools that the method
     * is intentionally unused.
     */

    @SuppressWarnings("unused")
    private static void unusedMethod() {
        System.out.println("This method is not called");
    }

    /*
     * @SuppressWarnings("all") requests suppression of all warning
     * categories recognized by the compiler for this method.
     *
     * This example is only for understanding the annotation.
     * In real projects, avoid suppressing all warnings unnecessarily.
     */

    @SuppressWarnings("all")
    private static void helperMethod() {
        Mobile mobObj = new Mobile();

        // The deprecation warning is suppressed within this method.
        mobObj.dummyMethod();
    }

    /*
     * We can suppress multiple categories together:
     *
     * @SuppressWarnings({"deprecation", "unused"})
     *
     * This suppresses both specified categories to the extent
     * they are recognized by the compiler or development tools.
     */
}